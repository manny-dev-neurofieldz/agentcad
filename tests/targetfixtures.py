"""What the contract suite needs to exercise each registered output target.

A target's capabilities take inputs: a job needs a base configuration (for a slicer target), reading
needs a file the target can read, a printer needs a configuration, slicing needs a project. This module
holds, per target name, a builder that makes them in a temporary folder. The contract suite asks for the
builder of every target that declares a capability, and a registered target with none fails the suite
(``MissingFixture``): a capability nobody exercised is a promise nobody checked.

Everything here is synthetic. The configuration is invented, not copied from any printer or slicer
profile; its credential values are placeholders to prove they never reach a project.
"""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Dict, Optional

from tests import gcode_fixtures


class MissingFixture(AssertionError):
    """A registered target declares capabilities and the suite has no fixture for it."""


