#: Settings a project must never carry, with values that are easy to look for.
PRIVATE: Dict[str, str] = {
    "printhost_apikey": "SYNTHETIC-KEY-0001",
    "printhost_user": "synthetic_user",
    "printhost_password": "synthetic-password",
    "printhost_cafile": "synthetic-ca.pem",
    "print_host": "192.0.2.10",
    "post_process": "synthetic_script.sh",
}


def synthetic_config(**changes: Optional[str]) -> Dict[str, str]:
    """The synthetic configuration with ``changes`` applied; a change to None removes the key."""
    config = dict(SYNTHETIC)
    for key, value in changes.items():
        if value is None:
            config.pop(key, None)
        else:
            config[key] = value
    return config


def write_ini(path: Path, config: Dict[str, str]) -> Path:
    """A flat ``.ini`` as PrusaSlicer exports one: a comment line, then ``key = value``."""
    path.write_text("# generated by a test\n" + "".join(f"{k} = {config[k]}\n" for k in sorted(config)))
    return path


def write_gcode(path: Path, config: Dict[str, str]) -> Path:
    """Plain G-code with a statistic, then the configuration block a slicer writes."""
    path.write_text("G1 X1 E1\n" + gcode_fixtures.trailer("1m 2s", 12.5, config))
    return path


def write_bgcode(path: Path, config: Dict[str, str]) -> Path:
    """A ``.bgcode`` whose slicer metadata is ``config``."""
    path.write_bytes(gcode_fixtures.bgcode_bytes(gcode_fixtures.BODY_B, config, "1m 2s", 12.5))
    return path


@dataclass
class TargetCase:
    """What to feed a target's capabilities."""
    options: Dict[str, Any] = field(default_factory=dict)   # Job.options for write_job
    intent: Dict[str, Any] = field(default_factory=dict)    # a neutral intent for map_intent
    sliced: Optional[Path] = None                           # a file read_settings reads ...
    expect: Dict[str, str] = field(default_factory=dict)    # ... and settings it must return from it
    config: Optional[Path] = None                           # a printer configuration for printer
    readback: Optional[str] = None                          # suffix of a written file read_settings must read too
    project: Optional[Path] = None                          # a project for slice


def _generic(tmp: Path) -> TargetCase:
    return TargetCase(intent={"layer_height": 0.2}, sliced=write_gcode(tmp / "generic.gcode", synthetic_config()),
                      expect={"layer_height": "0.25"})


def _prusaslicer(tmp: Path) -> TargetCase:
    config = synthetic_config(**PRIVATE)
    return TargetCase(options={"base_config": write_ini(tmp / "base.ini", config)},
                      intent={"layer_height": 0.15, "walls": 3, "infill_percent": 25, "supports": True,
                              "print_orientation": "flat"},
                      sliced=write_bgcode(tmp / "sliced.bgcode", config), expect={"perimeters": "2"},
                      config=tmp / "base.ini", readback=".3mf")


#: One builder per registered target name.
BUILDERS: Dict[str, Callable[[Path], TargetCase]] = {"generic": _generic, "prusaslicer": _prusaslicer}


def case_for(name: str, tmp: Path) -> TargetCase:
    """The inputs for a target's capabilities; MissingFixture when the suite has none for it."""
    if name not in BUILDERS:
        raise MissingFixture(f"target {name!r} declares capabilities but tests/targetfixtures.py has no entry for it: "
                             f"add one (what a job's options, a sliced file and a printer configuration look like)")
    return BUILDERS[name](tmp)
