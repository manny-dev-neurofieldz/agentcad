"""Synthetic sliced files for the gcode tests: plain G-code written as text, and .bgcode built byte by byte.

Two slices of one imaginary plate, small enough to total by hand.

Slice A has 0.2 mm layers (5 of them), a peg with a ledge held up by supports (bridge infill at z 1.0 over
support lines at z 0.2 and 0.4) and a plug. Extrusion, in mm of filament:

    priming 5, skirt 1, supports 2 + 2, peg perimeters 5 x 3, peg bridge infill 2, plug 2 x 1.5   = 30

Slice B has 0.3 mm layers (3 of them), no supports, the same peg and a cap instead of the plug:

    priming 5, skirt 1, peg perimeters 3 x 3 and solid infill 2, cap 3 x 1                          = 20

A states 1h 2m 3s, B 56m 22s. The statistics a plain file writes before its configuration block (filament,
time, extrusion widths, max_layer_z, objects_info) are here too: they are not settings and must never read as
settings.
Credentials and post-processing paths sit in each configuration so tests can prove they never leave.
"""

import struct
import zlib
from pathlib import Path
from typing import Dict, Optional, Union

from agentcad import cli
from tests.test_gcode_bgcode import block, heatshrink, meatpack   # the codec writers live with their tests

FRAME = ";LAYER_CHANGE\n;Z:{z}\n;HEIGHT:{h}\nG1 Z{z}\n{body}"


def _layer(z: float, h: float, body: str) -> str:
    return FRAME.format(z=z, h=h, body=body)


def _run(y: float, e: float, x1: float = 20) -> str:
    """A travel to (0, y), then one extruding line to (x1, y) pushing e mm of filament."""
    return f"G1 X0 Y{y}\nG1 X{x1} Y{y} E{e}\n"


SKIRT = ";TYPE:Skirt/Brim\n;WIDTH:0.5\nG1 X10 Y0 E1\n"
PEG = "M486 S0\n"
OTHER = "M486 S1\n"
NONE = "M486 S-1\n"
EXT = ";TYPE:External perimeter\n;WIDTH:0.45\n"
PERIM = ";TYPE:Perimeter\n;WIDTH:0.45\n"
SUPPORT = ";TYPE:Support material\n;WIDTH:0.45\n"
LEDGE = ";TYPE:Bridge infill\n;WIDTH:0.45\n"
SOLID = ";TYPE:Solid infill\n;WIDTH:0.45\n"

HEAD = ("; generated by a test\n\n; external perimeters extrusion width = 0.45mm\n"
        "M83\nM486 S0\nM486 Apeg.stl\nM486 S1\nM486 A{other}\nM486 S-1\n;TYPE:Custom\nG1 X0 Y-3 E5 F1000\n")

#: Slice A: 5 layers of 0.2 mm; the ledge at z 1.0 sits 0.6 mm over the supports of layer 1 (z 0.4).
BODY_A = (HEAD.format(other="plug.stl")
          + _layer(0.2, 0.2, SKIRT + PEG + SUPPORT + _run(5, 2) + EXT + _run(50, 3) + OTHER + PERIM + _run(80, 1.5) + NONE)
          + _layer(0.4, 0.2, PEG + SUPPORT + _run(5, 2) + EXT + _run(50, 3) + OTHER + PERIM + _run(80, 1.5) + NONE)
          + _layer(0.6, 0.2, PEG + EXT + _run(50, 3) + NONE)
          + _layer(0.8, 0.2, PEG + EXT + _run(50, 3) + NONE)
          + _layer(1.0, 0.2, PEG + LEDGE + _run(5, 2) + EXT + _run(50, 3) + NONE))

#: Slice B: 3 layers of 0.3 mm, no supports.
BODY_B = (HEAD.format(other="cap.stl")
          + _layer(0.3, 0.3, SKIRT + PEG + EXT + _run(50, 3) + SOLID + _run(55, 2) + OTHER + PERIM + _run(80, 1) + NONE)
          + _layer(0.6, 0.3, PEG + EXT + _run(50, 3) + OTHER + PERIM + _run(80, 1) + NONE)
          + _layer(0.9, 0.3, PEG + EXT + _run(50, 3) + OTHER + PERIM + _run(80, 1) + NONE))

TIME_A, TIME_B = "1h 2m 3s", "56m 22s"
SECONDS_A, SECONDS_B = 3723, 3382
FILAMENT_A, FILAMENT_B = 30.0, 20.0
GRAMS_A, GRAMS_B = 0.09, 0.06

